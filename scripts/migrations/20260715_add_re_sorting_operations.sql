-- ============================================================================
-- WMS: пересортица между двумя product_id в одной direct-локации
--
-- Бизнес-смысл:
--   from_product_id: -Q
--   to_product_id:   +Q
--   Q всегда целое и > 0, net delta операции = 0.
--
-- Этот файл является точным DB-контрактом для сервисной реализации.
-- Не переименовывать таблицы, поля и константные значения без отдельного решения.
--
-- Перед применением:
--   1. Сделать backup / проверить stage.
--   2. Убедиться, что активна партиция wms.movements для текущей даты.
--   3. Применять до запуска новой версии WMS Service.
-- ============================================================================

BEGIN;

-- --------------------------------------------------------------------------
-- 1. Разрешить отдельный operation_code в общей allow-list таблице
-- --------------------------------------------------------------------------

ALTER TABLE wms.operation_locations
    DROP CONSTRAINT IF EXISTS chk_operation_locations_operation_code;

ALTER TABLE wms.operation_locations
    ADD CONSTRAINT chk_operation_locations_operation_code
    CHECK (
        operation_code IN (
            'kit_operations',
            're_sorting_operations'
        )
    );

COMMENT ON TABLE wms.operation_locations IS
'Список WMS-локаций, на которых разрешены доменные операции. '
'Поддерживаемые operation_code: kit_operations, re_sorting_operations.';

COMMENT ON COLUMN wms.operation_locations.operation_code IS
'Код доменной операции: kit_operations или re_sorting_operations.';

-- --------------------------------------------------------------------------
-- 2. Разрешить movement_type=re_sorting
--
-- Constraint на partitioned parent распространяется на partitions.
-- Сохраняется полный текущий список типов движения и добавляется re_sorting.
-- --------------------------------------------------------------------------

ALTER TABLE wms.movements
    DROP CONSTRAINT IF EXISTS chk_movement_type;

ALTER TABLE wms.movements
    ADD CONSTRAINT chk_movement_type
    CHECK (
        movement_type IN (
            'receive',
            'putaway',
            'transfer',
            'pick',
            'ship',
            'unpack',
            'adjust',
            'kit_assembly',
            'kit_disassembly',
            're_sorting'
        )
    );

COMMENT ON COLUMN wms.movements.movement_type IS
'receive, putaway, transfer, pick, ship, unpack, adjust, '
'kit_assembly, kit_disassembly, re_sorting.';

COMMENT ON COLUMN wms.movements.source_type IS
'Тип доменной операции-источника movement. '
'Для пересортицы: re_sorting_operation; для комплектации: kit_operation.';

COMMENT ON COLUMN wms.movements.source_id IS
'ID доменной операции-источника. '
'Для source_type=re_sorting_operation это wms.re_sorting_operations.operation_id.';

COMMENT ON COLUMN wms.movements.source_item_id IS
'ID строки детализации доменной операции. '
'Для source_type=re_sorting_operation это wms.re_sorting_operation_items.item_id.';

-- --------------------------------------------------------------------------
-- 3. Заголовок операции пересортицы
-- --------------------------------------------------------------------------

CREATE TABLE wms.re_sorting_operations (
    operation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    operation_location_id bigint NOT NULL,

    from_product_id character varying(50) NOT NULL,
    to_product_id character varying(50) NOT NULL,

    quantity integer NOT NULL,

    location_id bigint NOT NULL,
    location_code character varying(100) NOT NULL,

    reason text NOT NULL,
    author character varying(100) NOT NULL,

    status character varying(32) NOT NULL DEFAULT 'processing',
    error_message text,

    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,

    created_at timestamp with time zone NOT NULL DEFAULT now(),
    completed_at timestamp with time zone,
    updated_at timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT chk_re_sorting_operation_products_different
        CHECK (from_product_id <> to_product_id),

    CONSTRAINT chk_re_sorting_operation_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_re_sorting_operation_reason
        CHECK (btrim(reason) <> ''),

    CONSTRAINT chk_re_sorting_operation_author
        CHECK (btrim(author) <> ''),

    CONSTRAINT chk_re_sorting_operation_status
        CHECK (status IN ('processing', 'completed', 'failed')),

    CONSTRAINT fk_re_sorting_operation_operation_location
        FOREIGN KEY (operation_location_id)
        REFERENCES wms.operation_locations(operation_location_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_re_sorting_operation_from_product
        FOREIGN KEY (from_product_id)
        REFERENCES public.products(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_re_sorting_operation_to_product
        FOREIGN KEY (to_product_id)
        REFERENCES public.products(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_re_sorting_operation_location
        FOREIGN KEY (location_id)
        REFERENCES wms.locations(location_id)
        ON DELETE RESTRICT
);

COMMENT ON TABLE wms.re_sorting_operations IS
'Атомарные WMS-операции пересортицы: одинаковое целое количество физического '
'loose-остатка переносится между двумя разными product_id на одной разрешённой '
'direct-локации. 1С и RabbitMQ не вызываются.';

COMMENT ON COLUMN wms.re_sorting_operations.operation_location_id IS
'Ссылка на активную allow-list строку wms.operation_locations '
'с operation_code=re_sorting_operations и scope=direct.';

COMMENT ON COLUMN wms.re_sorting_operations.from_product_id IS
'Исходный SKU/product_id, physical loose-остаток которого уменьшается.';

COMMENT ON COLUMN wms.re_sorting_operations.to_product_id IS
'Целевой SKU/product_id, physical loose-остаток которого увеличивается.';

COMMENT ON COLUMN wms.re_sorting_operations.quantity IS
'Целое положительное количество. Одинаково для исходящего и входящего movement.';

COMMENT ON COLUMN wms.re_sorting_operations.location_id IS
'Точная direct-локация операции; subtree дочерних адресов не используется.';

COMMENT ON COLUMN wms.re_sorting_operations.location_code IS
'Кешированный код использованной локации для аудита. Источник истины — location_id.';

COMMENT ON COLUMN wms.re_sorting_operations.status IS
'processing, completed, failed. В MVP business validation/conflict обычно '
'откатывает transaction и не сохраняет failed operation, аналогично kit flow.';

-- --------------------------------------------------------------------------
-- 4. Две строки операции: source_outgoing и target_incoming
-- --------------------------------------------------------------------------

CREATE TABLE wms.re_sorting_operation_items (
    item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    operation_id bigint NOT NULL,

    role character varying(64) NOT NULL,
    product_id character varying(50) NOT NULL,
    quantity integer NOT NULL,

    movement_id bigint,
    movement_created_at timestamp with time zone,

    created_at timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT chk_re_sorting_operation_item_role
        CHECK (role IN ('source_outgoing', 'target_incoming')),

    CONSTRAINT chk_re_sorting_operation_item_quantity
        CHECK (quantity > 0),

    CONSTRAINT uq_re_sorting_operation_item_role
        UNIQUE (operation_id, role),

    CONSTRAINT fk_re_sorting_operation_item_operation
        FOREIGN KEY (operation_id)
        REFERENCES wms.re_sorting_operations(operation_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_re_sorting_operation_item_product
        FOREIGN KEY (product_id)
        REFERENCES public.products(id)
        ON DELETE RESTRICT
);

COMMENT ON TABLE wms.re_sorting_operation_items IS
'Детализация пересортицы. У completed operation должно быть две строки: '
'source_outgoing и target_incoming с одинаковым quantity.';

COMMENT ON COLUMN wms.re_sorting_operation_items.role IS
'source_outgoing = списание from_product_id; '
'target_incoming = приход to_product_id.';

COMMENT ON COLUMN wms.re_sorting_operation_items.movement_id IS
'ID movement, созданного для строки. FK не задаётся, поскольку partitioned '
'wms.movements не имеет устойчивой parent PK/unique модели.';

COMMENT ON COLUMN wms.re_sorting_operation_items.movement_created_at IS
'created_at соответствующего movement; используется вместе с movement_id '
'для поиска нужной partitioned movement row.';

-- --------------------------------------------------------------------------
-- 5. Индексы
-- --------------------------------------------------------------------------

CREATE INDEX idx_re_sorting_operations_created_at
    ON wms.re_sorting_operations (created_at DESC);

CREATE INDEX idx_re_sorting_operations_status_created_at
    ON wms.re_sorting_operations (status, created_at DESC);

CREATE INDEX idx_re_sorting_operations_from_product
    ON wms.re_sorting_operations (from_product_id);

CREATE INDEX idx_re_sorting_operations_to_product
    ON wms.re_sorting_operations (to_product_id);

CREATE INDEX idx_re_sorting_operations_location
    ON wms.re_sorting_operations (location_id);

CREATE INDEX idx_re_sorting_operations_operation_location
    ON wms.re_sorting_operations (operation_location_id);

CREATE INDEX idx_re_sorting_operation_items_operation
    ON wms.re_sorting_operation_items (operation_id);

CREATE INDEX idx_re_sorting_operation_items_product
    ON wms.re_sorting_operation_items (product_id);

