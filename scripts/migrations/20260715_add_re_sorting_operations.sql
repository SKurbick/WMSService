COMMIT;

-- ============================================================================
-- POST-APPLY READ-ONLY VERIFICATION
-- ============================================================================

-- 1. Новые объекты
SELECT
    to_regclass('wms.re_sorting_operations') AS operations_table,
    to_regclass('wms.re_sorting_operation_items') AS items_table;

-- 2. Проверить допустимые operation_code
SELECT pg_get_constraintdef(oid) AS operation_code_constraint
FROM pg_constraint
WHERE conrelid = 'wms.operation_locations'::regclass
  AND conname = 'chk_operation_locations_operation_code';

-- 3. Проверить допустимые movement_type
SELECT pg_get_constraintdef(oid) AS movement_type_constraint
FROM pg_constraint
WHERE conrelid = 'wms.movements'::regclass
  AND conname = 'chk_movement_type';

-- 4. Проверить таблицы/колонки/типы
SELECT
    table_schema,
    table_name,
    column_name,
    data_type,
    is_nullable,
    column_default
FROM information_schema.columns
WHERE table_schema = 'wms'
  AND table_name IN (
      're_sorting_operations',
      're_sorting_operation_items'
  )
ORDER BY table_name, ordinal_position;

-- 5. Проверить constraints
SELECT
    c.conrelid::regclass AS table_name,
    c.conname,
    c.contype,
    pg_get_constraintdef(c.oid) AS definition
FROM pg_constraint c
WHERE c.conrelid IN (
    'wms.re_sorting_operations'::regclass,
    'wms.re_sorting_operation_items'::regclass
)
ORDER BY c.conrelid::regclass::text, c.conname;

-- 6. Проверить индексы
SELECT
    tablename,
    indexname,
    indexdef
FROM pg_indexes
WHERE schemaname = 'wms'
  AND tablename IN (
      're_sorting_operations',
      're_sorting_operation_items'
  )
ORDER BY tablename, indexname;

-- ============================================================================
-- AUDIT QUERIES ДЛЯ ПОСЛЕДУЮЩЕГО ИСПОЛЬЗОВАНИЯ
-- ============================================================================

-- A. Completed operations без двух items
SELECT
    rso.operation_id,
    COUNT(rsoi.item_id) AS item_count
FROM wms.re_sorting_operations rso
LEFT JOIN wms.re_sorting_operation_items rsoi
       ON rsoi.operation_id = rso.operation_id
WHERE rso.status = 'completed'
GROUP BY rso.operation_id
HAVING COUNT(rsoi.item_id) <> 2;

-- B. Completed operations без обеих обязательных ролей
SELECT
    rso.operation_id,
    COUNT(*) FILTER (WHERE rsoi.role = 'source_outgoing') AS source_count,
    COUNT(*) FILTER (WHERE rsoi.role = 'target_incoming') AS target_count
FROM wms.re_sorting_operations rso
LEFT JOIN wms.re_sorting_operation_items rsoi
       ON rsoi.operation_id = rso.operation_id
WHERE rso.status = 'completed'
GROUP BY rso.operation_id
HAVING COUNT(*) FILTER (WHERE rsoi.role = 'source_outgoing') <> 1
    OR COUNT(*) FILTER (WHERE rsoi.role = 'target_incoming') <> 1;

-- C. Items без movement reference
SELECT *
FROM wms.re_sorting_operation_items
WHERE movement_id IS NULL
   OR movement_created_at IS NULL;

-- D. Items с отсутствующим movement
SELECT
    rsoi.*
FROM wms.re_sorting_operation_items rsoi
LEFT JOIN wms.movements m
       ON m.movement_id = rsoi.movement_id
      AND m.created_at = rsoi.movement_created_at
WHERE rsoi.movement_id IS NOT NULL
  AND m.movement_id IS NULL;

-- E. Несовпадение item/header quantity или product role
SELECT
    rso.operation_id,
    rso.from_product_id,
    rso.to_product_id,
    rso.quantity AS operation_quantity,
    rsoi.item_id,
    rsoi.role,
    rsoi.product_id,
    rsoi.quantity AS item_quantity
FROM wms.re_sorting_operations rso
JOIN wms.re_sorting_operation_items rsoi
  ON rsoi.operation_id = rso.operation_id
WHERE rsoi.quantity <> rso.quantity
   OR (
       rsoi.role = 'source_outgoing'
       AND rsoi.product_id <> rso.from_product_id
   )
   OR (
       rsoi.role = 'target_incoming'
       AND rsoi.product_id <> rso.to_product_id
   );

-- F. Movements с неверными source/type/side/quantity
SELECT
    rso.operation_id,
    rsoi.item_id,
    rsoi.role,
    m.movement_id,
    m.movement_type,
    m.product_id,
    m.from_location_id,
    m.to_location_id,
    m.quantity,
    m.source_type,
    m.source_id,
    m.source_item_id
FROM wms.re_sorting_operations rso
JOIN wms.re_sorting_operation_items rsoi
  ON rsoi.operation_id = rso.operation_id
JOIN wms.movements m
  ON m.movement_id = rsoi.movement_id
 AND m.created_at = rsoi.movement_created_at
WHERE m.movement_type <> 're_sorting'
   OR m.source_type <> 're_sorting_operation'
   OR m.source_id <> rso.operation_id
   OR m.source_item_id <> rsoi.item_id
   OR m.product_id <> rsoi.product_id
   OR m.quantity <> rso.quantity
   OR (
       rsoi.role = 'source_outgoing'
       AND (
           m.from_location_id IS DISTINCT FROM rso.location_id
           OR m.to_location_id IS NOT NULL
       )
   )
   OR (
       rsoi.role = 'target_incoming'
       AND (
           m.from_location_id IS NOT NULL
           OR m.to_location_id IS DISTINCT FROM rso.location_id
       )
   );

-- G. Completed operations с ненулевым net delta
WITH movement_deltas AS (
    SELECT
        rso.operation_id,
        CASE
            WHEN rsoi.role = 'source_outgoing' THEN -m.quantity
            WHEN rsoi.role = 'target_incoming' THEN  m.quantity
            ELSE 0
        END AS delta
    FROM wms.re_sorting_operations rso
    JOIN wms.re_sorting_operation_items rsoi
      ON rsoi.operation_id = rso.operation_id
    JOIN wms.movements m
      ON m.movement_id = rsoi.movement_id
     AND m.created_at = rsoi.movement_created_at
    WHERE rso.status = 'completed'
)
SELECT
    operation_id,
    SUM(delta) AS net_delta
FROM movement_deltas
GROUP BY operation_id
HAVING SUM(delta) <> 0;

-- H. Active allow-list пересортицы указывает на inactive location
SELECT
    ol.operation_location_id,
    ol.location_id,
    ol.location_code
FROM wms.operation_locations ol
JOIN wms.locations l
  ON l.location_id = ol.location_id
WHERE ol.operation_code = 're_sorting_operations'
  AND ol.scope = 'direct'
  AND ol.is_active = true
  AND l.is_active = false;
